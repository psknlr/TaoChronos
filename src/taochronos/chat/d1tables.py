"""The data the D1 backup's JavaScript needs from this checkout, as one module (``cloud/site/src/backup/tables.js``).

The Worker (``cloud/site/src/backup/``) answers with the tools ported to JavaScript; what they read that is not the
corpus comes from here, generated, never copied by hand: the normaliser's tables (``VariantTable``: the character map
with OpenCC's and the curated variants, the word variants in the order they apply), the periods and the expressions
of time, the lexicon's category ranking, the historical terms and their senses, historical metrology, the safety
table and the modern evidence, the 要籍 list, the alias layer the full-corpus profile reads (ADR 0023: its records, the
sources they credit, the context its gates read and its parameters), and what the page is told — the tool catalog, the
standing instructions (with the corpus left as placeholders the Worker fills from the databases' statistics) and the
starters.

``python -m taochronos.chat.d1 tables`` writes it; ``--check`` (and the tests) fail when it no longer matches the
checkout, so that the Worker never normalises otherwise than the databases were built.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Callable

HEAD = ("// Generated by `python -m taochronos.chat.d1 tables` from this checkout (domains/, profiles/full-corpus.yaml,\n"
        "// corpus/catalog, the tool registry, taochronos.chat.prompt): do not edit.  The D1 backup's tools read it\n"
        "// (docs/adr/0017-d1-backup.md; the alias layer: docs/adr/0023-alias-layer.md).\n")


def _js(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


# tables written as a single-quoted JS string, not JSON: text of JSON lines, whose quotes then need no escaping
TEXTS = frozenset({"ALIASES"})
_QUOTE = {"\\": "\\\\", "'": "\\'", "\n": "\\n", "\r": "\\r", "\u2028": "\\u2028", "\u2029": "\\u2029"}


def _js_text(text: str) -> str:
    """``text`` as a single-quoted JS string literal: a backslash, the quote and the line terminators escaped."""
    return "'" + re.sub("[\\\\'\n\r\u2028\u2029]", lambda m: _QUOTE[m.group()], text) + "'"


def tables(home: str | Path | None = None) -> dict[str, Any]:
    """Every table the backup's JavaScript reads, by the name it exports."""
    from .. import __version__
    from ..config import find_home
    from ..plugins.classics.domain import CATEGORY_PRIORITY, DomainPack, PULSE_QUALITIES
    from ..protocol.yamlio import load_yaml
    from . import ChatRuntime
    from .catalog import CORE, ENGINE_TOOLS, FAMILIES, META_TOOLS, NEVER
    from .prompt import AGENT_NAME, ASSISTANT_NAME, PUBLISHER, STARTERS, system_prompt

    root = find_home(str(home) if home else None)
    pack = DomainPack(root / "domains" / "classics")
    v = pack.variants
    combined = {chr(k) if isinstance(k, int) else k: val for k, val in v._table.items()}
    periods = pack.periods
    out: dict[str, Any] = {
        "NORMALIZER": v.fingerprint,
        # normalize_text: this map, then the word variants in this order (each replacing every occurrence)
        "CHAR_MAP": dict(sorted(combined.items())),
        "WORDS": [[w["from"], w["to"], w.get("kind", "variant"), w.get("note", "")] for w in v.words],
        # normalize (with the record of what was changed): the curated characters, then the script map, then the words
        "CURATED": {k: [to, note] for k, (to, note) in sorted(v.chars.items())},
        "SCRIPT": dict(sorted(pack.script.map.items())),
        "WITNESS_WEIGHTS": v.witness_weights,
        "UNCERTAIN_MASS": v.uncertain_mass,
        "PERIODS": [[p.id, p.label, p.start, p.end] for p in periods.analysis],
        "DYNASTIES": [[d["name"], d["start"], d["end"]] for d in periods.dynasties],
        "EXPRESSIONS": {k: [r.start, r.end] for k, r in periods.expressions.items()},
        "CATEGORY_PRIORITY": CATEGORY_PRIORITY,
        "PULSE_QUALITIES": PULSE_QUALITIES,
        "TERMS": [_term(t, pack.terminology.sense_meta) for t in pack.terminology.terms.values()],
        "METROLOGY": load_yaml(pack.root / "metrology.yaml"),
        "SAFETY": (load_yaml(root / "domains" / "modern" / "safety.yaml") or {}).get("materials") or {},
        "CROSSWALK": load_yaml(root / "domains" / "modern" / "crosswalk.yaml") or {},
        "MODERN_RECORDS": (load_yaml(root / "corpus" / "modern" / "evidence.yaml") or {}).get("records") or [],
        "CANON": _canon(load_yaml(root / "corpus" / "catalog" / "canon.yaml") or {}),
        **_aliases(root),
    }
    # the catalog as the server offers it, every tool (the Worker keeps those it serves), and what the page is told
    runtime = ChatRuntime.create("full-discovery", home=root, ephemeral=True)
    catalog = runtime.catalog("all")
    out["CATALOG"] = {"tools": [t for t in catalog["tools"] if t["family"] not in ("engine",)],
                      "engine": ENGINE_TOOLS, "meta": META_TOOLS, "core": CORE, "never": sorted(NEVER),
                      "families": FAMILIES}
    info = {"corpus": {"kind": "full", "books": "{books}", "passages": "{passages}",
                       "canon": {"listed": "{listed}", "held": "{held}"}}}
    out["PROMPT"] = system_prompt(info)
    out["INFO"] = {"name": "TaoChronos", "version": __version__, "assistant_name": ASSISTANT_NAME, "agent_name": AGENT_NAME,
                   "publisher": PUBLISHER, "starters": STARTERS}
    return out


def _term(t: Any, meta: dict[str, dict[str, Any]]) -> dict[str, Any]:
    return {"id": t.id, "category": t.category, "related": list(t.related), "broader": list(t.broader), "notes": t.notes,
            "senses": [{"id": s.id, "label": s.label, "gloss": s.gloss, "category": s.category,
                        "period": [s.period.start, s.period.end] if s.period else None, "cues": list(s.cues),
                        "anti_cues": list(s.anti_cues), "scope": meta.get(s.id, {}).get("scope"),
                        "candidates": meta.get(s.id, {}).get("candidates", [])} for s in t.senses]}


def _aliases(root: Path) -> dict[str, Any]:
    """The alias layer as the full-corpus profile reads it (``backup/aliases.js`` decides from it as ``AliasIndex``
    does): ``ALIASES``, its records as the index holds them, in code-point order of their surfaces, one line each —
    the surface, a tab, then the record in the file's compact form without what no decision reads (the surface, the
    raw spellings, the floor's basis, a referent's note) — as one string, so that the Worker's start reads no record
    (a record is read when first used); ``ALIAS_INDEX``, what its lookups by group, head and term read of them
    (``aliases.layout``: positions are lines of ``ALIASES``); ``ALIAS_SOURCES``, the sources an answer may credit,
    [{id, label, licence}] — the shippable ones of sources.yaml, labelled as the files' headers label them;
    ``ALIAS_CONTEXT``, ``context.json`` over the default patterns; ``ALIAS_PARAMS``, ``DEFAULT_ALIAS`` under the
    profile's ``retrieval.alias``.  A profile that reads a local layer, or a record crediting a source that may not
    ship, is refused: nothing local reaches the Worker."""
    from ..plugins.classics.aliases import CONTEXT_PATTERNS, DEFAULT_ALIAS, AliasIndex, layout
    from ..protocol.yamlio import load_yaml

    profile = load_yaml(root / "profiles" / "full-corpus.yaml") or {}
    bundles = {b.get("plugin"): b.get("config") or {} for b in profile.get("bundles") or []}
    classics = bundles.get("taochronos.plugins.classics") or {}
    if classics.get("aliases_local"):
        raise ValueError("full-corpus reads a local alias layer (aliases_local): the Worker's tables never carry one")
    domain = root / classics.get("domain", "domains/classics")
    dirs = list(classics.get("aliases") or ())
    files = [domain / d / "aliases.jsonl" for d in dirs if (domain / d / "aliases.jsonl").exists()]
    context = next((domain / d / "context.json" for d in dirs if (domain / d / "context.json").exists()), None)
    index = AliasIndex.load(files, context=context) if files else AliasIndex.empty()
    registry = {s["id"]: s for d in dirs if (domain / d / "sources.yaml").exists()
                for s in (load_yaml(domain / d / "sources.yaml") or {}).get("sources") or []}
    shipped = [s for s in registry.values() if s.get("ship") is True]
    refused = sorted({src for rec in index.records.values() for ref in rec.r for src in ref.src}
                     - {s["id"] for s in shipped})
    if refused:
        raise ValueError(f"the alias layer credits sources that may not ship: {', '.join(refused)}")
    records = [index.records[s] for s in sorted(index.records)]
    lines = []
    for record in records:
        if "\t" in record.s or "\n" in record.s:
            raise ValueError(f"the alias layer's surface {record.s!r} holds a tab or a line break")
        rec = record.to_json()
        for key in ("s", "raw", "flb"):
            rec.pop(key, None)
        for ref in rec.get("r") or ():
            ref.pop("nt", None)
        lines.append(f"{record.s}\t{_js(rec)}")
    shape = layout(records)
    return {
        "ALIASES": "\n".join(lines),
        "ALIAS_INDEX": {key: shape[key] for key in ("groups", "headless", "heads", "owners", "terms", "stops")},
        "ALIAS_SOURCES": [{"id": s["id"], "label": index.labels.get(s["id"], s.get("label", s["id"])),
                           "licence": s.get("licence")} for s in shipped],
        "ALIAS_CONTEXT": {**CONTEXT_PATTERNS, **index.context},
        "ALIAS_PARAMS": {**DEFAULT_ALIAS, **((bundles.get("taochronos.plugins.retrieval") or {}).get("alias") or {})},
    }


def _canon(data: dict[str, Any]) -> dict[str, Any]:
    from ..plugins.classics.study.canon import METHOD

    keep = ("rank", "title", "authors", "dynasty", "composition", "category", "cited_by", "witnesses", "siku", "work")
    return {"method": METHOD, "works": [{k: w.get(k) for k in keep} for w in data.get("works") or []]}


def module(home: str | Path | None = None) -> str:
    parts = [HEAD]
    for name, value in tables(home).items():
        parts.append(f"export const {name} = {_js_text(value) if name in TEXTS else _js(value)};\n")
    return "".join(parts)


def write_tables(output: str | Path | None = None, *, check: bool = False, home: str | Path | None = None,
                 log: Callable[[str], None] = print) -> int:
    """Write (or with ``check``, compare) the Worker's tables module; what it did goes to ``log`` — a caller whose own
    output is a report on stdout (``taochronos web canon``) sends it elsewhere."""
    from ..config import find_home

    root = find_home(str(home) if home else None)
    path = Path(output) if output else root / "cloud" / "site" / "src" / "backup" / "tables.js"
    text = module(root)
    if check:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            log(f"{path} is not up to date: run python -m taochronos.chat.d1 tables")
            return 1
        log(f"{path}: up to date")
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    log(f"{path}: {len(text.encode('utf-8')):,} bytes")
    return 0


__all__ = ["module", "tables", "write_tables"]
